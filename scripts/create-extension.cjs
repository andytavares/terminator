// ── File generation ───────────────────────────────────────────────────────────

/** Writes the extension's files: `{ manifest, index, pkg }` are their contents. */
function writeExtension(dir, { manifest, index, pkg }) {
  fs.mkdirSync(path.join(dir, 'src'), { recursive: true })
  fs.writeFileSync(path.join(dir, 'package.json'), pkg, 'utf8')
  fs.writeFileSync(path.join(dir, 'manifest.json'), manifest, 'utf8')
  fs.writeFileSync(path.join(dir, 'src', 'index.js'), index, 'utf8')
}

// ── CLI ───────────────────────────────────────────────────────────────────────

function printHelp() {
  console.log(`
Usage: npm run create-extension -- <name> [options]

Arguments:
  <name>        Kebab-case extension name (e.g., my-extension)

Options:
  --id <id>     Reverse-domain ID (default: com.example.<name>)
  --dir <path>  Output directory (default: extensions/<name>)
  --help        Show this help message

Exit codes:
  0  Success
  1  Bad arguments
  2  Directory already exists
  3  Filesystem error
`)
}

/** Prints `message` and exits with `code`. */
function exitWithError(message, code) {
  console.error(message)
  process.exit(code)
}

/** The name, ID and output directory the arguments ask for; exits on a bad one. */
function parseArgs(args) {
  // Parse positional name argument
  const positional = args.filter((a) => !a.startsWith('--'))
  const name = positional[0]
  if (!name) {
    console.error('Error: Extension name is required.\n')
    printHelp()
    process.exit(1)
  }
  const nameError = validateName(name)
  if (nameError) exitWithError(`Error: ${nameError}`, 1)

  const idIdx = args.indexOf('--id')
  const id = idIdx !== -1 ? args[idIdx + 1] : `com.example.${name}`
  const idError = validateId(id)
  if (idError) exitWithError(`Error: ${idError}`, 1)

  const dirIdx = args.indexOf('--dir')
  const outDir =
    dirIdx !== -1 ? path.resolve(args[dirIdx + 1]) : path.resolve(process.cwd(), 'extensions', name)
  return { name, id, outDir }
}

